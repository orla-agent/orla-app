import * as esbuild from 'esbuild';
import fs from 'fs';
const raw = { name: 'raw', setup(b) {
  b.onResolve({ filter: /\?raw$/ }, (a) => ({ path: new URL(a.path.replace(/\?raw$/, ''), 'file://' + a.resolveDir + '/').pathname, namespace: 'raw' }));
  b.onLoad({ filter: /.*/, namespace: 'raw' }, (a) => ({ contents: fs.readFileSync(a.path, 'utf8'), loader: 'text' }));
} };
await esbuild.build({
  entryPoints: ['src/worker.js'], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  outfile: 'dist/worker.js', minify: process.argv.includes('--min'), legalComments: 'none',
  mainFields: ['module', 'main'], conditions: ['worker', 'browser', 'import'],
  loader: { '.txt': 'text', '.css': 'text', '.json': 'json' }, plugins: [raw],
  banner: { js: '// ORLA — single-file Cloudflare Worker. Generated by build.mjs; edit src/ and rebuild.' },
});
const s = fs.statSync('dist/worker.js').size;
console.log('dist/worker.js', (s / 1024).toFixed(0), 'KB');
